"""Build SciLab.exe (PyInstaller) and the Windows installer (Inno Setup).

Usage (from the repository root, with the 64-bit build environment):

    .venv-build\\Scripts\\python.exe packaging\\build.py            # exe + installer
    .venv-build\\Scripts\\python.exe packaging\\build.py --skip-installer
    .venv-build\\Scripts\\python.exe packaging\\build.py --skip-exe  # re-pack an existing dist\\SciLab
    .venv-build\\Scripts\\python.exe packaging\\build.py --clean     # also clear PyInstaller's cache

Steps:
  1. Regenerate packaging/file_version_info.txt from scilab_version.__version__.
  2. PyInstaller with packaging/SciLab.spec  ->  dist/SciLab/SciLab.exe (one-folder app).
  3. Inno Setup (ISCC.exe) with packaging/SciLab.iss  ->  dist/installer/SciLab-Setup-<version>.exe

Requirements: a 64-bit Python with the app requirements + pyinstaller (the
.venv-build folder), and Inno Setup 6 (ISCC.exe found via %ISCC%, PATH, or the
default Program Files locations).
"""

from __future__ import annotations

import argparse
import os
import shutil
import struct
import subprocess
import sys
import time
from pathlib import Path

PACKAGING_DIR = Path(__file__).resolve().parent
ROOT = PACKAGING_DIR.parent
DIST_DIR = ROOT / "dist"
BUILD_DIR = ROOT / "build"
APP_DIST_DIR = DIST_DIR / "SciLab"
INSTALLER_DIR = DIST_DIR / "installer"
SPEC_FILE = PACKAGING_DIR / "SciLab.spec"
ISS_FILE = PACKAGING_DIR / "SciLab.iss"
VERSION_INFO_FILE = PACKAGING_DIR / "file_version_info.txt"

sys.path.insert(0, str(ROOT))
from scilab_version import APP_NAME, COMPANY, DESCRIPTION, __version__, version_tuple  # noqa: E402


VERSION_INFO_TEMPLATE = """# UTF-8
#
# Generated by packaging/build.py from scilab_version.py -- do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tuple},
    prodvers={tuple},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo([
      StringTable(
        "040904B0",
        [
          StringStruct("CompanyName", "{company}"),
          StringStruct("FileDescription", "{description}"),
          StringStruct("FileVersion", "{version}"),
          StringStruct("InternalName", "{app}"),
          StringStruct("LegalCopyright", "Copyright (C) {company}"),
          StringStruct("OriginalFilename", "{app}.exe"),
          StringStruct("ProductName", "{app}"),
          StringStruct("ProductVersion", "{version}"),
        ],
      )
    ]),
    VarFileInfo([VarStruct("Translation", [1033, 1200])]),
  ],
)
"""


def log(msg: str) -> None:
    print(f"[build] {msg}", flush=True)


def write_version_info() -> None:
    text = VERSION_INFO_TEMPLATE.format(
        tuple=version_tuple(),
        version=__version__,
        company=COMPANY,
        description=DESCRIPTION,
        app=APP_NAME,
    )
    VERSION_INFO_FILE.write_text(text, encoding="utf-8")
    log(f"version {__version__} -> {VERSION_INFO_FILE.relative_to(ROOT)}")


def run(cmd: list[str], cwd: Path) -> None:
    log("$ " + " ".join(f'"{c}"' if " " in c else c for c in cmd))
    subprocess.run(cmd, cwd=str(cwd), check=True)


def build_exe(clean: bool) -> Path:
    if struct.calcsize("P") * 8 != 64:
        raise SystemExit("Build with a 64-bit Python: OceanDirect.dll and the vendor DLLs are x64.")
    try:
        import PyInstaller  # noqa: F401
    except ImportError as exc:
        raise SystemExit(f"PyInstaller is not installed in {sys.executable}: {exc}") from exc

    if APP_DIST_DIR.exists():
        shutil.rmtree(APP_DIST_DIR)
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm",
        "--distpath", str(DIST_DIR),
        "--workpath", str(BUILD_DIR),
        str(SPEC_FILE),
    ]
    if clean:
        cmd.insert(3, "--clean")
    t0 = time.time()
    run(cmd, cwd=ROOT)
    exe = APP_DIST_DIR / f"{APP_NAME}.exe"
    if not exe.is_file():
        raise SystemExit(f"PyInstaller finished but {exe} is missing.")
    log(f"exe ready: {exe.relative_to(ROOT)} ({exe.stat().st_size / 1e6:.1f} MB) in {time.time() - t0:.0f}s")
    return exe


def find_iscc() -> Path | None:
    candidates = []
    env = os.environ.get("ISCC", "").strip().strip('"')
    if env:
        candidates.append(Path(env))
    on_path = shutil.which("ISCC.exe") or shutil.which("iscc")
    if on_path:
        candidates.append(Path(on_path))
    for pf in (os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles")):
        if pf:
            candidates.append(Path(pf) / "Inno Setup 6" / "ISCC.exe")
    for c in candidates:
        if c.is_file():
            return c
    return None


def build_installer() -> Path:
    iscc = find_iscc()
    if iscc is None:
        raise SystemExit("ISCC.exe (Inno Setup 6) not found. Install Inno Setup or set %ISCC%.")
    if not (APP_DIST_DIR / f"{APP_NAME}.exe").is_file():
        raise SystemExit(f"{APP_DIST_DIR} does not contain {APP_NAME}.exe; run without --skip-exe first.")
    INSTALLER_DIR.mkdir(parents=True, exist_ok=True)
    cmd = [
        str(iscc),
        f"/DMyAppVersion={__version__}",
        f"/DSourceDir={APP_DIST_DIR}",
        f"/DOutputDir={INSTALLER_DIR}",
        f"/DRepoDir={ROOT}",
        str(ISS_FILE),
    ]
    t0 = time.time()
    run(cmd, cwd=PACKAGING_DIR)
    setup = INSTALLER_DIR / f"{APP_NAME}-Setup-{__version__}.exe"
    if not setup.is_file():
        raise SystemExit(f"ISCC finished but {setup} is missing.")
    log(f"installer ready: {setup.relative_to(ROOT)} ({setup.stat().st_size / 1e6:.1f} MB) in {time.time() - t0:.0f}s")
    return setup


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--skip-exe", action="store_true", help="do not run PyInstaller (re-use dist/SciLab)")
    parser.add_argument("--skip-installer", action="store_true", help="do not run Inno Setup")
    parser.add_argument("--clean", action="store_true", help="pass --clean to PyInstaller")
    args = parser.parse_args(argv)

    log(f"{APP_NAME} {__version__} using {sys.executable}")
    write_version_info()
    if not args.skip_exe:
        build_exe(clean=args.clean)
    if not args.skip_installer:
        build_installer()
    log("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
