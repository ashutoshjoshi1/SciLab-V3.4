"""Build the SciLab executable and the Windows installer.

    python packaging/build.py              # frozen app + installer
    python packaging/build.py --app-only   # frozen app only
    python packaging/build.py --clean      # discard build/ and dist/ first

Run it with the interpreter that has the runtime dependencies *and*
PyInstaller -- ``.venv-build`` in this checkout (see packaging/README.md).
Everything version-shaped is derived from ``scilab_version.py``, so a release
is one edit there plus a rebuild.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGING = ROOT / "packaging"
sys.path.insert(0, str(ROOT))

from scilab_version import (  # noqa: E402
    APP_ID,
    APP_NAME,
    COPYRIGHT,
    DISPLAY_VERSION,
    EXE_NAME,
    PRODUCT_NAME,
    PUBLISHER,
    PUBLISHER_URL,
    VERSION,
    VERSION_TUPLE,
)

VERSION_INFO = PACKAGING / "file_version_info.txt"
SPEC = PACKAGING / "SciLab.spec"
ISS = PACKAGING / "installer.iss"
DIST_APP = ROOT / "dist" / EXE_NAME
DIST_INSTALLER = ROOT / "dist" / "installer"

# Inno Setup's compiler. Both install locations are checked, then PATH.
ISCC_CANDIDATES = (
    Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
    Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
)


def log(message: str) -> None:
    print(f"[build] {message}", flush=True)


def write_version_resource() -> None:
    """Generate the VERSIONINFO block PyInstaller stamps into the .exe.

    Windows shows these fields in the file's Properties > Details tab, and
    installers and inventory tools read them, so they must match the installer
    exactly -- hence generating instead of hand-maintaining.
    """
    major, minor, patch, build = VERSION_TUPLE
    content = f'''# UTF-8
#
# Generated by packaging/build.py from scilab_version.py -- do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, {build}),
    prodvers=({major}, {minor}, {patch}, {build}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo([
      StringTable(
        "040904B0",
        [
          StringStruct("CompanyName", "{PUBLISHER}"),
          StringStruct("FileDescription", "{PRODUCT_NAME}"),
          StringStruct("FileVersion", "{VERSION}"),
          StringStruct("InternalName", "{EXE_NAME}"),
          StringStruct("LegalCopyright", "{COPYRIGHT}"),
          StringStruct("OriginalFilename", "{EXE_NAME}.exe"),
          StringStruct("ProductName", "{APP_NAME}"),
          StringStruct("ProductVersion", "{VERSION}"),
        ],
      )
    ]),
    VarFileInfo([VarStruct("Translation", [1033, 1200])]),
  ],
)
'''
    VERSION_INFO.write_text(content, encoding="utf-8")
    log(f"version resource -> {VERSION_INFO.name} ({VERSION})")


def ensure_icon() -> None:
    """Regenerate the multi-resolution icon from the logo if it is missing."""
    icon = PACKAGING / "scilab.ico"
    if icon.is_file():
        return
    log("icon missing; regenerating from sciglob_logoRGB.png")
    from PIL import Image

    logo = Image.open(ROOT / "sciglob_logoRGB.png").convert("RGBA")
    mark = logo.crop((0, 0, 449, logo.height))
    mark = mark.crop(mark.getchannel("A").getbbox())
    side = int(max(mark.size) * 1.10)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(mark, ((side - mark.width) // 2, (side - mark.height) // 2), mark)
    sizes = [256, 128, 64, 48, 32, 24, 16]
    canvas.resize((sizes[0], sizes[0]), Image.Resampling.LANCZOS).save(
        icon, format="ICO", sizes=[(s, s) for s in sizes]
    )


def ensure_wizard_images() -> None:
    """Render the installer's side banner and header badge.

    Inno Setup only accepts uncompressed BMP here, so they are generated from
    the PNG logo rather than kept as binaries in the repo.
    """
    from PIL import Image

    logo = Image.open(ROOT / "sciglob_logoRGB.png").convert("RGBA")
    mark = logo.crop((0, 0, 449, logo.height))
    mark = mark.crop(mark.getchannel("A").getbbox())

    # Side banner, 164x314 at 100% scaling (Inno scales it for HiDPI).
    banner_path = PACKAGING / "wizard_banner.bmp"
    banner = Image.new("RGB", (164, 314), "#ffffff")
    scaled = mark.copy()
    scaled.thumbnail((120, 120), Image.Resampling.LANCZOS)
    banner.paste(scaled, ((164 - scaled.width) // 2, 40), scaled)
    wordmark = logo.copy()
    wordmark.thumbnail((140, 40), Image.Resampling.LANCZOS)
    banner.paste(wordmark, ((164 - wordmark.width) // 2, 190), wordmark)
    banner.save(banner_path, format="BMP")

    # Header badge shown on every page after the first, 55x55 at 100%.
    small_path = PACKAGING / "wizard_small.bmp"
    small = Image.new("RGB", (55, 55), "#ffffff")
    badge = mark.copy()
    badge.thumbnail((47, 47), Image.Resampling.LANCZOS)
    small.paste(badge, ((55 - badge.width) // 2, (55 - badge.height) // 2), badge)
    small.save(small_path, format="BMP")
    log("wizard images -> wizard_banner.bmp, wizard_small.bmp")


def find_iscc() -> Path | None:
    for candidate in ISCC_CANDIDATES:
        if candidate.is_file():
            return candidate
    found = shutil.which("ISCC")
    return Path(found) if found else None


def run(command: list[str], cwd: Path) -> None:
    log(" ".join(str(part) for part in command))
    result = subprocess.run(command, cwd=str(cwd))
    if result.returncode != 0:
        raise SystemExit(f"[build] FAILED ({result.returncode}): {command[0]}")


def build_app(clean: bool) -> None:
    command = [sys.executable, "-m", "PyInstaller", "--noconfirm"]
    if clean:
        command.append("--clean")
    command += ["--distpath", str(ROOT / "dist"), "--workpath", str(ROOT / "build"), str(SPEC)]
    run(command, ROOT)

    exe = DIST_APP / f"{EXE_NAME}.exe"
    if not exe.is_file():
        raise SystemExit(f"[build] FAILED: {exe} was not produced")
    size_mb = sum(f.stat().st_size for f in DIST_APP.rglob("*") if f.is_file()) / (1024 * 1024)
    log(f"app -> {DIST_APP}  ({size_mb:.0f} MB)")


def verify_app() -> None:
    """Smoke-test the frozen build before wrapping it in an installer.

    Shipping a bundle that cannot import its own backends is the classic
    PyInstaller failure, and it is invisible until someone tries to connect an
    instrument. ``--self-test`` exercises exactly that, without a display.
    """
    exe = DIST_APP / f"{EXE_NAME}.exe"
    log("self-test of the frozen bundle")
    result = subprocess.run([str(exe), "--self-test"], capture_output=True, text=True, timeout=300)
    output = (result.stdout or "") + (result.stderr or "")
    print(output.strip())
    if result.returncode != 0:
        raise SystemExit(f"[build] FAILED: frozen self-test returned {result.returncode}")


def build_installer() -> None:
    iscc = find_iscc()
    if iscc is None:
        log("SKIPPED installer: Inno Setup 6 not found.")
        log("  Install it (winget install JRSoftware.InnoSetup) and re-run.")
        return
    DIST_INSTALLER.mkdir(parents=True, exist_ok=True)
    run(
        [
            str(iscc),
            f"/DMyAppId={APP_ID}",
            f"/DMyAppName={APP_NAME}",
            f"/DMyAppVersion={VERSION}",
            f"/DMyAppDisplayVersion={DISPLAY_VERSION}",
            f"/DMyAppPublisher={PUBLISHER}",
            f"/DMyAppUrl={PUBLISHER_URL}",
            f"/DMyProductName={PRODUCT_NAME}",
            f"/DMyExeName={EXE_NAME}.exe",
            f"/DMySourceDir={DIST_APP}",
            f"/DMyOutputDir={DIST_INSTALLER}",
            str(ISS),
        ],
        ROOT,
    )
    produced = sorted(DIST_INSTALLER.glob("*.exe"))
    for item in produced:
        log(f"installer -> {item}  ({item.stat().st_size / (1024 * 1024):.0f} MB)")
    if not produced:
        raise SystemExit("[build] FAILED: no installer produced")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app-only", action="store_true", help="skip the installer step")
    parser.add_argument("--clean", action="store_true", help="delete build/ and dist/ first")
    parser.add_argument("--skip-verify", action="store_true", help="skip the frozen self-test")
    args = parser.parse_args()

    if args.clean:
        for path in (ROOT / "build", ROOT / "dist"):
            if path.exists():
                log(f"removing {path}")
                shutil.rmtree(path, ignore_errors=True)

    os.chdir(ROOT)
    ensure_icon()
    write_version_resource()
    build_app(args.clean)
    if not args.skip_verify:
        verify_app()
    if not args.app_only:
        ensure_wizard_images()
        build_installer()
    log("done")


if __name__ == "__main__":
    main()
